#!/usr/bin/env bash
# Build the pipeline conda env.
#
#   envs/build.sh labrag              # resolve from pyproject.toml, then write the lock file
#   envs/build.sh labrag --from-lock  # reproduce exactly from envs/labrag.lock.txt
#
# labrag = pipeline (embed, label, classify, prompts, generate client) + dev tools.
# The evaluation metrics run as containers, not in a conda env.
#
# Envs go to the first entry of CONDA_ENVS_PATH (default ~/miniforge3/envs). The repo is
# installed editable, so the env must see the repo at the same path it was built from.
set -euo pipefail

usage="usage: envs/build.sh labrag [--from-lock]"
name=${1:?$usage}
mode=${2:-}
repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
envs_dir=${CONDA_ENVS_PATH:-$HOME/miniforge3/envs}
prefix=${envs_dir%%:*}/$name
lock=$repo/envs/$name.lock.txt
python_version=3.12

case $name in
  labrag) extras=pipeline,dev ;;
  *) echo "unknown env: $name" >&2; exit 1 ;;
esac

if [[ -e $prefix ]]; then
  echo "$prefix already exists; remove it first" >&2
  exit 1
fi

conda create -y -p "$prefix" -c conda-forge --override-channels "python=$python_version" pip
pip=("$prefix/bin/python" -m pip)

if [[ $mode == --from-lock ]]; then
  "${pip[@]}" install -r "$lock"
  "${pip[@]}" install --no-deps -e "$repo"
else
  "${pip[@]}" install -e "$repo[$extras]"
  {
    echo "# $name: generated by envs/build.sh on $(date -u +%F) (python $python_version)"
    # `pip list --format=freeze`, not `pip freeze`: conda-installed packages would be
    # pinned as `pkg @ file:///home/conda/...` paths that exist on no other node.
    "${pip[@]}" list --format=freeze --exclude-editable
  } > "$lock"
  echo "wrote $lock"
fi
